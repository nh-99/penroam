//! Font metrics and deterministic plain-text wrapping, shared with the TS port in
//! `apps/desktop-mobile/src/editor/textLayout.ts`. Text blocks are laid out by
//! [`crate::markdown`], which applies these wrapping rules to styled text.
//!
//! Widths come from `data/text-metrics.json` (the Liberation faces, metric-compatible
//! with Helvetica and Courier, and Excalifont for handwritten text), never from the
//! platform's font rasteriser, so wrapping is identical on every OS and in exported PDFs.
//! Golden: `tests/fixtures/text-layout-golden.json`.
//!
//! Excalifont has one face. Its bold and italic ([`Face::HandBold`] and friends) are
//! drawn by thickening and slanting that face, the same way on screen and in PDFs, so
//! they keep its widths exactly. [`Face::styled`] picks the face for one character: one
//! the handwritten font has no glyph for is set in the formatted font instead, so the
//! layout never measures a glyph that a renderer would take from some other font.
//!
//! Rules: `\n` forces a break; otherwise greedy wrapping at spaces; a word
//! wider than the box is broken between characters; trailing spaces of a
//! wrapped line do not count towards its width.

use crate::model::TextFont;
use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::sync::OnceLock;

/// The bundled metrics file (generated by `tools/gen-font-metrics.mjs`).
pub const METRICS_JSON: &str = include_str!("../data/text-metrics.json");

/// Font metrics in font units (see `units_per_em`).
#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct TextMetrics {
    /// Font units per em (1000 for Liberation Sans metrics).
    pub units_per_em: f64,
    /// Ascender height.
    pub ascent: f64,
    /// Descender depth.
    pub descent: f64,
    /// Distance between baselines.
    pub line_height: f64,
    /// Baseline of the first line, measured from the top of the box.
    pub first_baseline: f64,
    /// Advance used for characters without a metric.
    pub fallback_width: f64,
    /// Advance per code point (decimal string keys in the JSON).
    widths: HashMap<String, f64>,
    /// Advances of the other faces (same shape as `widths`).
    faces: FaceWidths,
    /// The handwritten font.
    hand: HandMetrics,
    #[serde(skip)]
    by_char: HashMap<char, f64>,
    #[serde(skip)]
    by_face: [HashMap<char, f64>; 5],
}

#[derive(Debug, Deserialize)]
struct HandMetrics {
    ascent: f64,
    descent: f64,
    widths: HashMap<String, f64>,
}

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
struct FaceWidths {
    bold: HashMap<String, f64>,
    italic: HashMap<String, f64>,
    bold_italic: HashMap<String, f64>,
    mono: HashMap<String, f64>,
}

/// A bundled typeface. The formatted faces each have a standard PDF font with the
/// same widths; the handwritten ones are embedded in PDFs.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize)]
#[serde(rename_all = "camelCase")]
pub enum Face {
    /// Liberation Sans Regular / Helvetica.
    Regular,
    /// Liberation Sans Bold / Helvetica-Bold.
    Bold,
    /// Liberation Sans Italic / Helvetica-Oblique.
    Italic,
    /// Liberation Sans Bold Italic / Helvetica-BoldOblique.
    BoldItalic,
    /// Liberation Mono / Courier.
    Mono,
    /// Excalifont.
    Hand,
    /// Excalifont, thickened.
    HandBold,
    /// Excalifont, slanted.
    HandItalic,
    /// Excalifont, thickened and slanted.
    HandBoldItalic,
}

impl Face {
    /// The face for character `c` of text in `font` with the given emphasis.
    /// Code is always [`Face::Mono`]; handwritten text uses the formatted faces
    /// for characters Excalifont doesn't have.
    pub fn styled(font: TextFont, bold: bool, italic: bool, mono: bool, c: char) -> Face {
        if mono {
            return Face::Mono;
        }
        let m = metrics();
        let hand = font == TextFont::Handwritten
            && (m.by_face[4].contains_key(&c) || c == '\t' && m.by_face[4].contains_key(&' '));
        match (hand, bold, italic) {
            (false, false, false) => Face::Regular,
            (false, true, false) => Face::Bold,
            (false, false, true) => Face::Italic,
            (false, true, true) => Face::BoldItalic,
            (true, false, false) => Face::Hand,
            (true, true, false) => Face::HandBold,
            (true, false, true) => Face::HandItalic,
            (true, true, true) => Face::HandBoldItalic,
        }
    }

    /// Whether this is one of the handwritten faces.
    pub fn is_hand(self) -> bool {
        matches!(
            self,
            Face::Hand | Face::HandBold | Face::HandItalic | Face::HandBoldItalic
        )
    }
}

/// Horizontal shear of the slanted handwritten faces: x moves this far right
/// per unit of height above the baseline.
pub const HAND_SLANT: f64 = 0.2;

/// Width of the outline stroke that thickens the bold handwritten faces, in em.
/// Half of it lands outside the glyph.
pub const HAND_BOLD_STROKE: f64 = 0.045;

/// Size of code relative to the text around it.
pub const MONO_SCALE: f64 = 0.9;

fn char_map(widths: &HashMap<String, f64>) -> HashMap<char, f64> {
    widths
        .iter()
        .filter_map(|(k, v)| {
            k.parse::<u32>()
                .ok()
                .and_then(char::from_u32)
                .map(|c| (c, *v))
        })
        .collect()
}

/// The bundled metrics, parsed once.
pub fn metrics() -> &'static TextMetrics {
    static M: OnceLock<TextMetrics> = OnceLock::new();
    M.get_or_init(|| {
        let mut m: TextMetrics = serde_json::from_str(METRICS_JSON).expect("text-metrics.json");
        m.by_char = char_map(&m.widths);
        m.by_face = [
            char_map(&m.faces.bold),
            char_map(&m.faces.italic),
            char_map(&m.faces.bold_italic),
            char_map(&m.faces.mono),
            char_map(&m.hand.widths),
        ];
        m
    })
}

impl TextMetrics {
    /// Advance width of one character in em/1000 units.
    pub fn advance(&self, c: char) -> f64 {
        if c == '\t' {
            return self.advance(' ') * 4.0;
        }
        *self.by_char.get(&c).unwrap_or(&self.fallback_width)
    }
    /// Advance width of one character of `face` in em/1000 units.
    pub fn advance_in(&self, face: Face, c: char) -> f64 {
        let map = match face {
            Face::Regular => return self.advance(c),
            Face::Bold => &self.by_face[0],
            Face::Italic => &self.by_face[1],
            Face::BoldItalic => &self.by_face[2],
            Face::Mono => &self.by_face[3],
            Face::Hand | Face::HandBold | Face::HandItalic | Face::HandBoldItalic => {
                &self.by_face[4]
            }
        };
        if c == '\t' {
            return self.advance_in(face, ' ') * 4.0;
        }
        *map.get(&c).unwrap_or(&self.fallback_width)
    }
    /// Whether the character has a metric (and a WinAnsi glyph in Helvetica).
    pub fn known(&self, c: char) -> bool {
        self.by_char.contains_key(&c)
    }
    /// Whether `face` has a glyph for the character. The formatted faces answer
    /// as [`TextMetrics::known`]: the PDF's standard fonts share one character set.
    pub fn known_in(&self, face: Face, c: char) -> bool {
        if face.is_hand() {
            self.by_face[4].contains_key(&c)
        } else {
            self.known(c)
        }
    }
    /// Ascender height of `font`'s text faces, in font units.
    pub fn ascent_of(&self, font: TextFont) -> f64 {
        match font {
            TextFont::Formatted => self.ascent,
            TextFont::Handwritten => self.hand.ascent,
        }
    }
    /// Descender depth of `font`'s text faces (negative), in font units.
    pub fn descent_of(&self, font: TextFont) -> f64 {
        match font {
            TextFont::Formatted => self.descent,
            TextFont::Handwritten => self.hand.descent,
        }
    }
    /// Line height in points at `font_size`.
    pub fn line_height(&self, font_size: f64) -> f64 {
        font_size * self.line_height / self.units_per_em
    }
    /// Offset of the first baseline from the box top, in points.
    pub fn first_baseline(&self, font_size: f64) -> f64 {
        font_size * self.first_baseline / self.units_per_em
    }
}

/// One laid-out line.
#[derive(Debug, Clone, PartialEq, serde::Serialize)]
pub struct Line {
    /// Character (not byte) range into the source text.
    pub start: usize,
    /// End of the range (exclusive).
    pub end: usize,
    /// The line's text.
    pub text: String,
    /// Width in points, excluding trailing spaces.
    pub width: f64,
}

/// Width of `s` in points at `font_size` (no wrapping).
pub fn measure(s: &str, font_size: f64) -> f64 {
    let m = metrics();
    s.chars().map(|c| m.advance(c)).sum::<f64>() * font_size / m.units_per_em
}

/// Lays `text` out in a box `box_width` points wide.
pub fn layout(text: &str, font_size: f64, box_width: f64) -> Vec<Line> {
    let m = metrics();
    let scale = font_size / m.units_per_em;
    let chars: Vec<char> = text.chars().collect();
    let mut lines = Vec::new();
    let mut para_start = 0;
    loop {
        let para_end = chars[para_start..]
            .iter()
            .position(|&c| c == '\n')
            .map(|i| para_start + i)
            .unwrap_or(chars.len());
        wrap_paragraph(
            &chars, para_start, para_end, box_width, scale, m, &mut lines,
        );
        if para_end >= chars.len() {
            break;
        }
        para_start = para_end + 1;
    }
    lines
}

fn wrap_paragraph(
    chars: &[char],
    start: usize,
    end: usize,
    box_w: f64,
    scale: f64,
    m: &TextMetrics,
    out: &mut Vec<Line>,
) {
    let push = |out: &mut Vec<Line>, s: usize, e: usize| {
        // trim trailing spaces from the measured width (not from the text range)
        let mut te = e;
        while te > s && chars[te - 1] == ' ' {
            te -= 1;
        }
        let width = chars[s..te].iter().fold(0.0, |a, &c| a + m.advance(c)) * scale;
        // rounded so the TS port and the golden file agree bit-for-bit
        let width = (width * 1e6).round() / 1e6 + 0.0;
        out.push(Line {
            start: s,
            end: e,
            text: chars[s..e].iter().collect(),
            width,
        });
    };
    if start == end {
        push(out, start, end);
        return;
    }
    let mut line_start = start;
    let mut i = start;
    let mut width = 0.0; // width of chars[line_start..i]
    let mut last_break: Option<usize> = None; // index after a space
    while i < end {
        let c = chars[i];
        let w = m.advance(c) * scale;
        if c == ' ' {
            width += w;
            i += 1;
            last_break = Some(i);
            continue;
        }
        if width + w > box_w && i > line_start {
            if let Some(b) = last_break.filter(|&b| b > line_start) {
                push(out, line_start, b);
                line_start = b;
            } else {
                push(out, line_start, i);
                line_start = i;
            }
            last_break = None;
            width = chars[line_start..i]
                .iter()
                .map(|&c| m.advance(c))
                .sum::<f64>()
                * scale;
            continue;
        }
        width += w;
        i += 1;
    }
    push(out, line_start, end);
}

/// Laid-out content height for a text block.
pub fn content_height(text: &str, font_size: f64, box_width: f64) -> f64 {
    let n = layout(text, font_size, box_width).len().max(1);
    n as f64 * metrics().line_height(font_size)
}
