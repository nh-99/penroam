#!/usr/bin/env python3
"""Writes android/gradle/verification-metadata.xml from the local Gradle cache.

The Onyx Maven repository only works over plain HTTP: its HTTPS endpoint offers a Diffie-Hellman
key that TLS clients refuse. Anything fetched from it could be swapped in transit, so the groups
it serves are pinned by SHA-256, and a changed file stops the build. Every other group comes over
HTTPS from Maven Central or Google and stays trusted.

Run this after changing an Onyx version, on a build that has resolved it, and review the diff:
a hash that changed for an existing version means the file changed, and that is not routine.
`patch-android.py` copies the result into the generated Android project.
"""
import hashlib, pathlib, re
from xml.sax.saxutils import quoteattr

ROOT = pathlib.Path(__file__).resolve().parents[3]
CACHE = pathlib.Path.home() / ".gradle/caches/modules-2/files-2.1"
GROUPS = re.compile(r"^(com\.onyx.*|pub\.devrel|com\.tencent|com\.jakewharton\.hugo\.fix)$")
# Gradle's first-match rule: trust every group except those above.
TRUST = r"^(?!com\.onyx|pub\.devrel$|com\.tencent$|com\.jakewharton\.hugo\.fix$).*$"

lines = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<verification-metadata xmlns="https://schema.gradle.org/dependency-verification"'
    ' xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"'
    ' xsi:schemaLocation="https://schema.gradle.org/dependency-verification'
    ' https://schema.gradle.org/dependency-verification/dependency-verification-1.3.xsd">',
    "  <!-- Generated by apps/desktop-mobile/scripts/pin-onyx-sdk.py -->",
    "  <configuration>",
    "    <verify-metadata>true</verify-metadata>",
    "    <verify-signatures>false</verify-signatures>",
    "    <trusted-artifacts>",
    f"      <trust group={quoteattr(TRUST)} regex=\"true\"/>",
    "    </trusted-artifacts>",
    "  </configuration>",
    "  <components>",
]
for group in sorted(p for p in CACHE.iterdir() if GROUPS.match(p.name)):
    for name in sorted(p for p in group.iterdir()):
        for version in sorted(p for p in name.iterdir()):
            lines.append(f'    <component group="{group.name}" name="{name.name}" version="{version.name}">')
            for artifact in sorted(version.glob("*/*"), key=lambda f: f.name):
                digest = hashlib.sha256(artifact.read_bytes()).hexdigest()
                lines += [
                    f'      <artifact name="{artifact.name}">',
                    f'        <sha256 value="{digest}" origin="pinned from repo.boox.com"/>',
                    "      </artifact>",
                ]
            lines.append("    </component>")
lines += ["  </components>", "</verification-metadata>", ""]
out = ROOT / "android/gradle/verification-metadata.xml"
out.write_text("\n".join(lines))
print(f"wrote {out}")
